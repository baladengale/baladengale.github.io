// bala.dengale — shared site behaviour
(function () {
  // Ensure the theme attribute is set even if the inline <head> script didn't run.
  var root = document.documentElement;
  var saved = null;
  try { saved = localStorage.getItem("theme"); } catch (e) {}
  if (!root.hasAttribute("data-theme")) {
    root.setAttribute("data-theme", saved === "light" ? "light" : "dark");
  }

  document.addEventListener("DOMContentLoaded", async () => {
    // footer year
    document.querySelectorAll("#year, .yr").forEach(e => (e.textContent = new Date().getFullYear()));

    // theme toggle (top-right of nav)
    const btn = document.getElementById("theme-toggle");
    if (btn) {
      const sync = () => btn.setAttribute("aria-pressed", root.getAttribute("data-theme") === "light" ? "true" : "false");
      sync();
      btn.addEventListener("click", () => {
        const next = root.getAttribute("data-theme") === "dark" ? "light" : "dark";
        root.setAttribute("data-theme", next);
        try { localStorage.setItem("theme", next); } catch (e) {}
        sync();
      });
    }

    // mobile hamburger menu
    const header = document.querySelector(".site-header");
    const navToggle = document.getElementById("nav-toggle");
    if (header && navToggle) {
      const setOpen = (open) => {
        header.classList.toggle("nav-open", open);
        navToggle.setAttribute("aria-expanded", open ? "true" : "false");
      };
      navToggle.addEventListener("click", (e) => {
        e.stopPropagation();
        setOpen(!header.classList.contains("nav-open"));
      });
      header.querySelectorAll(".site-nav ul a").forEach(a =>
        a.addEventListener("click", () => setOpen(false)));
      document.addEventListener("keydown", e => {
        if (e.key === "Escape") setOpen(false);
      });
      document.addEventListener("click", e => {
        if (header.classList.contains("nav-open") && !header.contains(e.target)) setOpen(false);
      });
    }

    // gallery lightbox (life page)
    const lightbox = document.querySelector(".lightbox");
    if (lightbox) {
      const img = lightbox.querySelector("img");
      const cap = lightbox.querySelector(".lb-caption");
      const close = () => lightbox.classList.remove("open");
      document.querySelectorAll(".gallery figure").forEach(fig => {
        fig.addEventListener("click", () => {
          const el = fig.querySelector("img");
          if (!el) return;
          img.src = el.src;
          img.alt = el.alt || "";
          const caption = fig.querySelector("figcaption");
          cap.textContent = caption ? caption.textContent.trim() : "";
          lightbox.classList.add("open");
        });
      });
      lightbox.addEventListener("click", close);
      lightbox.querySelector(".lb-close").addEventListener("click", e => {
        e.stopPropagation();
        close();
      });
      document.addEventListener("keydown", e => {
        if (e.key === "Escape") close();
      });
    }

    // home page: render latest 3 posts from the manifest generated by build.py
    const list = document.getElementById("latest-posts");
    if (!list) return;
    try {
      const res = await fetch("/blog/posts.json");
      if (!res.ok) throw new Error(res.status);
      const posts = await res.json();
      list.innerHTML = posts.slice(0, 3).map(p => {
        const tags = p.tags_list.map(t => `<span class="tag-sm">${t}</span>`).join("");
        const date = p.date ? new Date(p.date).toLocaleDateString("en-SG", { day: "numeric", month: "short", year: "numeric" }) : "";
        return `
          <a class="post-card" href="/blog/${p.slug}/">
            <div class="meta"><span>${date}</span><span class="dot">•</span><span>${p.reading_minutes} min read</span><span class="dot">•</span>${tags}</div>
            <h2>${p.title}</h2>
            <p class="excerpt">${p.excerpt || ""}</p>
          </a>`;
      }).join("");
    } catch (e) {
      list.innerHTML = '<p style="color:var(--text-dim)">Could not load posts — run <code>python3 build.py</code> to regenerate.</p>';
    }
  });
})();
